// Bundle the shared HTML without runtime file access in Cloudflare Workers.
import {readFileSync,writeFileSync} from 'node:fs';
// Normalise line endings: a Windows checkout (core.autocrlf) must produce the same bundle as CI.
const html=readFileSync(new URL('../../dashboard.html',import.meta.url),'utf8').replace(/\r\n/g,'\n');
writeFileSync(new URL('../src/dashboard-shell.js',import.meta.url),'// Generated by scripts/build-dashboard.js; edit analytics/dashboard.html.\nexport default '+JSON.stringify(html)+';\n');
